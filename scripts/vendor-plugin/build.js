#!/usr/bin/env node
'use strict';

/**
 * Builds the third-party libraries the image library plugin
 * (src/plugins/markport-clipper) loads on demand, into self-contained files
 * next to its main.js:
 *
 *   vendor-three.js          three.js, its model loaders (glTF, OBJ+MTL, FBX,
 *                            STL, PLY, 3MF, Collada, USDZ), OrbitControls,
 *                            RoomEnvironment, GLTFExporter, the meshopt decoder
 *   vendor-draco-decoder.js  Draco decoder, plain-JS build (for Draco glTFs)
 *   vendor-decoders.js       ag-psd (PSD/PSB), utif2 (TIFF), fflate (zip)
 *   vendor-heif.js           libheif-js (HEIC/HEIF), WebAssembly included
 *   vendor-licenses.txt      their license notices
 *
 * The plugin reads a vendor file through the vault adapter and evaluates it
 * (see loadVendor in main.js), which works the same in desktop Obsidian,
 * Markport server vaults and Markport in-browser vaults. That is why every
 * file is plain-text JavaScript in CommonJS form (module.exports), with no
 * imports, workers or .wasm files beside it.
 *
 * Versions are pinned in package.json. Usage:
 *
 *   cd scripts/vendor-plugin && npm install && npm run build
 */

const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const OUT = path.resolve(__dirname, '..', '..', 'src', 'plugins', 'markport-clipper');
const pkg = (name) => require(path.join(__dirname, 'node_modules', name, 'package.json'));

const banner = (what) => '/* ' + what + ' - generated by scripts/vendor-plugin/build.js, do not edit. Licenses: vendor-licenses.txt */';

async function bundle(outName, contents, what) {
  await esbuild.build({
    stdin: { contents, resolveDir: __dirname, loader: 'js' },
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    // three's loaders compute default decoder URLs from import.meta.url at
    // load time; give them a harmless base (main.js points them at real files).
    define: { 'import.meta.url': '"https://markport.invalid/vendor/"' },
    banner: { js: banner(what) },
    outfile: path.join(OUT, outName),
    logLevel: 'warning',
  });
  const size = fs.statSync(path.join(OUT, outName)).size;
  console.log(outName.padEnd(26) + (size / 1024).toFixed(0).padStart(6) + ' KB');
}

async function main() {
  const three = pkg('three').version;
  await bundle('vendor-three.js', `
    export * as THREE from 'three';
    export { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
    export { DRACOLoader } from 'three/addons/loaders/DRACOLoader.js';
    export { OBJLoader } from 'three/addons/loaders/OBJLoader.js';
    export { MTLLoader } from 'three/addons/loaders/MTLLoader.js';
    export { FBXLoader } from 'three/addons/loaders/FBXLoader.js';
    export { STLLoader } from 'three/addons/loaders/STLLoader.js';
    export { PLYLoader } from 'three/addons/loaders/PLYLoader.js';
    export { ThreeMFLoader } from 'three/addons/loaders/3MFLoader.js';
    export { ColladaLoader } from 'three/addons/loaders/ColladaLoader.js';
    export { USDLoader } from 'three/addons/loaders/USDLoader.js';
    export { OrbitControls } from 'three/addons/controls/OrbitControls.js';
    export { RoomEnvironment } from 'three/addons/environments/RoomEnvironment.js';
    export { GLTFExporter } from 'three/addons/exporters/GLTFExporter.js';
    export { MeshoptDecoder } from 'three/addons/libs/meshopt_decoder.module.js';
    export const version = ${JSON.stringify(three)};
  `, 'three.js ' + three);

  const draco = path.join(__dirname, 'node_modules', 'three', 'examples', 'jsm', 'libs', 'draco', 'gltf', 'draco_decoder.js');
  fs.writeFileSync(path.join(OUT, 'vendor-draco-decoder.js'), banner('Draco decoder (three.js ' + three + ')') + '\n' + fs.readFileSync(draco, 'utf8'));
  console.log('vendor-draco-decoder.js'.padEnd(26) + (fs.statSync(path.join(OUT, 'vendor-draco-decoder.js')).size / 1024).toFixed(0).padStart(6) + ' KB');

  // libheif (HEIC/HEIF, iPhone photos): its own self-contained build, with the
  // WebAssembly inside the file. Loaded only when a HEIC needs decoding.
  const heifSrc = path.join(__dirname, 'node_modules', 'libheif-js', 'libheif-wasm', 'libheif-bundle.js');
  fs.writeFileSync(path.join(OUT, 'vendor-heif.js'), banner('libheif-js ' + pkg('libheif-js').version + ' (LGPL-3.0)') + '\n' + fs.readFileSync(heifSrc, 'utf8'));
  console.log('vendor-heif.js'.padEnd(26) + (fs.statSync(path.join(OUT, 'vendor-heif.js')).size / 1024).toFixed(0).padStart(6) + ' KB');

  await bundle('vendor-decoders.js', `
    export { readPsd, initializeCanvas } from 'ag-psd';
    export * as UTIF from 'utif2';
    export { unzipSync } from 'fflate';
    export const versions = ${JSON.stringify({ 'ag-psd': pkg('ag-psd').version, utif2: pkg('utif2').version, fflate: pkg('fflate').version })};
  `, 'ag-psd, utif2, fflate');

  const licenses = [];
  for (const name of ['three', 'ag-psd', 'utif2', 'fflate', 'libheif-js']) {
    const dir = path.join(__dirname, 'node_modules', name);
    const file = fs.readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
    licenses.push('='.repeat(78) + '\n' + name + ' ' + pkg(name).version + (pkg(name).license ? ' (' + pkg(name).license + ')' : '') + '\n' + '='.repeat(78) + '\n\n'
      + (file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : 'License: ' + pkg(name).license) + '\n');
  }
  licenses.push('='.repeat(78) + '\nDraco decoder (bundled with three.js) - Apache License 2.0\nhttps://github.com/google/draco/blob/main/LICENSE\n');
  fs.writeFileSync(path.join(OUT, 'vendor-licenses.txt'), licenses.join('\n'));
}

main().catch((e) => { console.error(e); process.exit(1); });
